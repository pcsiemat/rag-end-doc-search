
from langgraph.graph import StateGraph, END
from rag_doc_search.state.rag_state import RAGState
from rag_doc_search.nodes.node import RAGNodes

class GraphBuilder:
    """
    Builds a state graph for the RAG pipeline.

    The graph consists of three states:
        1. question: The user's question.
        2. retrieved_docs: Chunks retrieved from the vector store.
        3. answer: The final answer generated by the LLM."""

    def __init__(self, retriever, llm):
        """Initializes the GraphBuilder with a retriever and an LLM.
        
        Args:
            retriever: The retriever to fetch documents.
            llm: The language model to generate answers.
        """
        self.nodes = RAGNodes(retriever, llm)
        self.graph = None

    def build(self):
        """ Build the RAG workflow grapgh
        
        Returns:
            Compiled graph instance.
        """

        # Create state graph
        builder = StateGraph(RAGState)

        # Add nodes
        builder.add_node("retriever", self.nodes.retrieve_docs)
        builder.add_node("responder", self.nodes.generate_answer)

        # Set entry point
        builder.set_entry_point("retriever")

        # Add edges
        builder.add_edge("retriever", "responder")
        builder.add_edge("responder", END)

        # Compile graph
        self.graph = builder.compile()
        return self.graph

    def run(self, question: str) -> dict:
        """
        Run the RAG workflow
        
        Args:
            question: User question
            
        Returns:
            Final state with answer
        """
        if self.graph is None:
            self.build()
        
        initial_state = RAGState(question=question)
        return self.graph.invoke(initial_state)




