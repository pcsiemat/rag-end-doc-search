"""RAG state management"""
from typing import List
from pydantic import BaseModel
from langchain_core.documents import Document


class RAGState(BaseModel):
    """
    Holds the data of one question as it moves through the RAG pipeline.

    Flow:
        1. question        → set by the user
        2. retrieved_docs  → filled by the retriever
        3. answer          → filled by the LLM

    Attributes:
        question: The user's question (required).
        retrieved_docs: Chunks retrieved from the vector store.
        answer: The final answer generated by the LLM.

    Example:
        >>> state = RAGState(question="What is RAG?")
        >>> state.retrieved_docs = retriever.invoke(state.question)
        >>> state.answer = "RAG combine search and generation..."
    """

    question: str
    retrieved_docs: List[Document] = []
    answer: str = ""